"""Write docs/MODEL-CARD.md from reports/metrics.json (every number traces to the committed report)."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def render(
    m: dict[str, Any],
    splits: list[dict[str, Any]],
    selection: list[dict[str, Any]] | None = None,
    served: dict[str, Any] | None = None,
    hardware: str | None = None,
) -> str:
    t, tta, slide, onnx = m["test"], m["test_tta8"], m["test_slide_level"], m["onnx"]
    op95 = t["operating_points"]["specificity_95_on_valid"]
    op50 = t["operating_points"]["balanced_0.5"]
    lines = [
        "# Model card: lymph-node metastasis patch classifier",
        "",
        "Generated by `python -m pcam.model_card` from `reports/metrics.json`, `reports/onnx-test.json` and the "
        "selection runs in `reports/`.",
        "",
        "## Model",
        "",
        f"- {m['model']}; trained {m['generated_at'][:10]} on {hardware or ', '.join(m['gpus']) or 'CPU'}, "
        f"{m['epochs_run']} epochs in {m['train_seconds'] / 60:.1f} minutes.",
        f"- Input: one 96x96 RGB patch, raw 0-255 values. Output: one logit; probability = sigmoid(logit / "
        f"{m['temperature']:.3f}) (temperature fitted on the validation split).",
        f"- Served as ONNX (opset {onnx['opset']}, {onnx['onnx_bytes'] / 1e6:.1f} MB) by the Rust service. Largest "
        f"difference from TensorFlow on {onnx['parity_patches']:,} test patches: {onnx['max_abs_probability_diff']:.2e} "
        "in probability.",
        "",
        "## Intended use",
        "",
        "Research and demonstration: highlight regions of lymph-node sections that may contain metastatic tissue so a "
        "pathologist looks there first. **Not a medical device and not validated for diagnosis.**",
        "",
        "## Data",
        "",
        "PatchCamelyon (Veeling et al., 2018; CC0), from the Camelyon16 challenge slides, published splits used "
        "unchanged.",
        "",
        "| Split | Patches | Tumour share | Slides |",
        "|---|---|---|---|",
        *[f"| {s['split']} | {s['patches']:,} | {pct(s['positive_share'])} | {s['slides']} |" for s in splits],
        "",
        "## Results on the held-out test split (scored once)",
        "",
        "| Metric | TensorFlow, single pass | 8-way test-time augmentation |",
        "|---|---|---|",
        f"| AUC (95% CI) | {t['auc']:.4f} ({t['auc_ci95'][0]:.4f}-{t['auc_ci95'][1]:.4f}) | "
        f"{tta['auc']:.4f} ({tta['auc_ci95'][0]:.4f}-{tta['auc_ci95'][1]:.4f}) |",
        f"| Accuracy at 0.5 | {pct(op50['accuracy'])} | {pct(tta['operating_points']['balanced_0.5']['accuracy'])} |",
        f"| Sensitivity / specificity at 0.5 | {pct(op50['sensitivity'])} / {pct(op50['specificity'])} | "
        f"{pct(tta['operating_points']['balanced_0.5']['sensitivity'])} / "
        f"{pct(tta['operating_points']['balanced_0.5']['specificity'])} |",
        f"| Sensitivity at the validation 95%-specificity threshold | {pct(op95['sensitivity'])} "
        f"(specificity on test {pct(op95['specificity'])}) | "
        f"{pct(tta['operating_points']['specificity_95_on_valid']['sensitivity'])} |",
        f"| ECE (calibrated on validation) | {t['ece']:.4f} | {tta['ece']:.4f} |",
        "",
        f"Validation AUC was {m['valid']['auc']:.4f}; the test split comes from different slides, and the gap shows it.",
        f"Calibration did not transfer: ECE {m['test_uncalibrated']['ece']:.4f} before temperature scaling and "
        f"{t['ece']:.4f} after, on test. Read the probabilities as scores, not as calibrated risks.",
        "",
    ]
    if served:
        vs = served["vs_tensorflow"]
        flips = vs["decisions_changed_at_threshold"]["balanced_0.5"]
        lines += [
            "### The exported model the service runs",
            "",
            f"All {served['patches']:,} test patches through the float32 ONNX export ({served['runtime']}): "
            f"**AUC {served['auc']:.4f}** ({served['auc_ci95'][0]:.4f}-{served['auc_ci95'][1]:.4f}) against "
            f"{vs['auc_tensorflow']:.4f} for TensorFlow. Probabilities differ by {vs['mean_abs_probability_diff']:.5f} "
            f"on average and at most {vs['max_abs_probability_diff']:.4f} (float16 training against a float32 export); "
            f"{flips} of {served['patches']:,} decisions at 0.5 change. Scored at "
            f"{served['patches_per_second']:,.0f} patches/s.",
            "",
        ]
    if "auc_max_patch" in slide:
        lines += [
            f"Slide level ({slide['slides']} test slides, {slide['tumour_slides']} with tumour; slide score = its "
            f"highest patch probability): AUC {slide['auc_max_patch']:.3f} "
            f"(95% CI {slide['auc_ci95'][0]:.3f}-{slide['auc_ci95'][1]:.3f}). Only patches PCam sampled are scored, "
            "not the whole slide.",
            "",
        ]
    if selection:
        lines += [
            "## Model selection (validation split only)",
            "",
            "Each learning rate was trained with early stopping on validation AUC and scored on the validation split; "
            "the test split was read once, by the final run of the chosen one.",
            "",
            "| Learning rate | Best epoch | Validation AUC | Training time |",
            "|---|---|---|---|",
            *[
                f"| {r['lr']:g} | {r['best_epoch']} of {r['epochs_run']} | {r['valid_auc_best_weights']:.4f} | "
                f"{r['train_seconds'] / 60:.1f} min |"
                for r in sorted(selection, key=lambda r: -r["lr"])
            ],
            "",
            f"The final run of the chosen rate stopped after {m['epochs_run']} epochs at validation AUC "
            f"{m['valid']['auc']:.4f}. GPU kernels are not bit-for-bit deterministic, so a rerun with the same seed "
            "can peak at a different epoch; early stopping chose the epoch on validation either way.",
            "",
        ]
    lines += [
        "## Limitations",
        "",
        "- PCam patches come from one challenge (two Dutch medical centres, Camelyon16); other scanners, stains and "
        "tissues will shift the inputs. Stain augmentation reduces but does not remove this.",
        "- The label is tumour in the centre 32x32 pixels; patches with tumour only at the edges are labelled "
        "negative.",
        "- PCam's original splits contain duplicate patches from probabilistic sampling; results are comparable with "
        "the PCam paper, which used the same splits.",
        "- The served model runs a single pass; test-time augmentation is measured above but costs 8x the compute.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--reports", type=Path, required=True)
    p.add_argument("--splits", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--hardware", help="what the training ran on, e.g. the GPU model from nvidia-smi")
    a = p.parse_args()
    m = json.loads((a.reports / "metrics.json").read_text())
    splits = json.loads(a.splits.read_text())
    selection = [json.loads(f.read_text()) for f in sorted(a.reports.glob("selection-lr*.json"))]
    served_path = a.reports / "onnx-test.json"
    served = json.loads(served_path.read_text()) if served_path.exists() else None
    a.out.write_text(render(m, splits, selection, served, a.hardware), encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
